import { test, expect } from '@playwright/test';

for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 844 }]) {
test(`complete workflow ${viewport.width}: private submission → review → publication → resolution; rejection excluded`, async ({ page, request }) => {
  await page.setViewportSize(viewport);
  const navigation = page.getByRole('navigation', { name: viewport.width < 1001 ? 'Mobile navigation' : 'Main navigation' });
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  const health = await request.get('/api/health'); expect(health.status()).toBe(200);
  const barangays = (await (await request.get('/api/reference/barangays')).json()).data;
  const categories = (await (await request.get('/api/reference/categories')).json()).data;
  expect(barangays).toHaveLength(180); expect(categories).toHaveLength(9);
  const before = (await (await request.get('/api/public/summary')).json()).data.total;
  await page.goto('/#report');
  await page.getByLabel('Barangay', { exact: true }).selectOption(barangays[0].psgc);
  await page.getByLabel('Category', { exact: true }).selectOption('natural_hazards');
  await page.getByLabel('Severity', { exact: true }).selectOption('moderate');
  await page.getByLabel('Incident date').fill('2026-01-01');
  await page.getByLabel('Incident time').fill('12:30');
  await page.getByLabel(/Description/).fill('AUTOMATED LOCAL TEST — isolated test database only. No real incident.');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Submit incident report' }).click();
  await expect(page.getByRole('heading', { name: 'Report submitted' })).toBeVisible();
  const reference = await page.locator('.reference-code').innerText();
  expect(reference).toMatch(/^ILO-\d{8}-[A-F0-9]{24}$/);
  expect((await (await request.get('/api/public/summary')).json()).data.total).toBe(before);
  await page.getByRole('button', { name: 'Open Local Demo Review' }).click();
  const card = page.locator('article').filter({ has: page.getByRole('heading', { name: reference, exact: true }) });
  await expect(card.getByText(/AUTOMATED LOCAL TEST/)).toBeVisible();
  await card.getByRole('button', { name: 'Start review' }).click();
  await expect(card.locator('.status-badge')).toContainText('Under Review');
  expect((await (await request.get('/api/public/summary')).json()).data.total).toBe(before);
  await card.getByRole('button', { name: 'Verify and publish' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button', { name: 'Confirm change' }).click();
  await expect(card.locator('.status-badge')).toContainText('Verified · Published');
  await navigation.getByRole('link', { name: 'Overview' }).click();
  await expect(page.getByTestId('published-total')).toHaveText(String(before + 1));
  await expect(page.getByRole('button', { name: 'Zoom in', exact: true })).toBeEnabled();
  await page.getByRole('combobox', { name: 'Explore a barangay' }).selectOption(barangays[0].psgc);
  await expect(page.getByText(`Published incidents: ${before + 1}`, { exact: true })).toBeVisible();
  await page.getByLabel('Severity filter').selectOption('critical');
  await expect(page.getByTestId('published-total')).toHaveText('0');
  await page.getByRole('button', { name: 'Reset filters' }).click();
  await expect(page.getByTestId('published-total')).toHaveText(String(before + 1));
  const publicBody = await (await request.get('/api/public/summary')).text();
  expect(publicBody).not.toMatch(/description|AUTOMATED LOCAL TEST|note_private|incident_id|public_reference/);
  await navigation.getByRole('link', { name: /Local Demo Review/ }).click();
  await card.getByRole('button', { name: 'Mark Responding' }).click();
  await expect(card.locator('.status-badge')).toContainText('Responding');
  await card.getByRole('button', { name: 'Resolve', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm change' }).click();
  await expect(card.locator('.status-badge')).toContainText('Resolved · Published');
  await card.getByText('Status history (5)', { exact: true }).click();
  await expect(card.getByRole('listitem')).toHaveCount(5);

  const submitted = await request.post('/api/incidents', { data: { barangayPsgc: barangays[1].psgc, categoryCode: 'other', severity: 'low', occurredAt: '2026-01-01T00:00:00Z', description: 'AUTOMATED REJECTION FIXTURE — isolated database only.' } });
  expect(submitted.status()).toBe(201);
  const rejectedReference = (await submitted.json()).data.reference;
  await page.getByRole('button', { name: 'Refresh queue' }).click();
  const rejected = page.locator('article').filter({ has: page.getByRole('heading', { name: rejectedReference, exact: true }) });
  await rejected.getByRole('button', { name: 'Reject', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm change' }).click();
  await expect(rejected.locator('.status-badge')).toContainText('Rejected · Private');
  expect((await (await request.get('/api/public/summary')).json()).data.total).toBe(before + 1);
  const review = (await (await request.get('/api/dev/incidents')).json()).data.items;
  const resolved = review.find((v: { public_reference: string }) => v.public_reference === reference);
  expect((await request.patch(`/api/dev/incidents/${resolved.id}/status`, { data: { status: 'responding', publish: true } })).status()).toBe(409);
  expect(errors).toEqual([]);
});
}
