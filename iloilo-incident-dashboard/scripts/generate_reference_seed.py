#!/usr/bin/env python3
"""Generate reference-only SQL from validated Phase 2 exports. No DB connection."""
import json
from pathlib import Path
from export_spatial import validate_outputs

ROOT = Path(__file__).resolve().parents[1]
CATEGORIES = [
    ('natural_hazards', 'Natural Hazards'), ('fire_rescue', 'Fire and Rescue'),
    ('medical_public_health', 'Medical and Public Health'), ('public_safety', 'Public Safety'),
    ('road_transportation', 'Road and Transportation'), ('infrastructure_utilities', 'Infrastructure and Utilities'),
    ('environmental', 'Environmental'), ('social_community_welfare', 'Social and Community Welfare'),
    ('other', 'Other'),
]


def sql(value):
    return "'" + value.replace("'", "''") + "'"


def main():
    output = ROOT / 'public/data'
    validate_outputs(output)
    features = json.loads((output / 'barangay_nodes.geojson').read_text())['features']
    lines = ['-- Generated by scripts/generate_reference_seed.py from validated Phase 2 nodes.',
             '-- Coordinates belong to barangay reference data only; no incident records.',
             'INSERT INTO barangays(psgc,name,representative_longitude,representative_latitude) VALUES']
    values = []
    for feature in sorted(features, key=lambda item: item['properties']['adm4_psgc']):
        props = feature['properties']
        lon, lat = feature['geometry']['coordinates']
        values.append(f"({sql(props['adm4_psgc'])},{sql(props['adm4_en'])},{lon!r},{lat!r})")
    lines.append(',\n'.join(values) + ';')
    lines.append('INSERT INTO incident_categories(code,label,display_order) VALUES')
    lines.append(',\n'.join(f'({sql(code)},{sql(label)},{index})'
                           for index, (code, label) in enumerate(CATEGORIES, start=1)) + ';')
    path = ROOT / 'migrations/0002_reference_data.sql'
    path.write_text('\n'.join(lines) + '\n')
    print(f'Generated {path.name}: {len(features)} barangays, {len(CATEGORIES)} categories; no incidents.')


if __name__ == '__main__':
    main()
